function add(n1, n2)
{
    let result;

    result = n1 + n2;
    return (result);
}

function subtract(n1, n2)
{
    let result;

    result = n1 - n2;
    return (result);
}

function multiply(n1, n2)
{
    let result;

    result = n1 * n2;
    return (result);
}

function divide(n1, n2)
{
    let result;

    result = n1 / n2;
    return (result);
}